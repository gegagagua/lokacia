export function rng(seed: number) {
  let a = seed >>> 0;
  const next = () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  return {
    next,
    int: (min: number, max: number) => Math.floor(next() * (max - min + 1)) + min,
    float: (min: number, max: number, digits = 2) => Number((next() * (max - min) + min).toFixed(digits)),
    pick: <T>(arr: readonly T[]): T => arr[Math.floor(next() * arr.length)] as T,
    chance: (p: number) => next() < p,
    shuffle: <T>(arr: T[]): T[] => {
      const c = [...arr];
      for (let i = c.length - 1; i > 0; i--) {
        const j = Math.floor(next() * (i + 1));
        [c[i], c[j]] = [c[j] as T, c[i] as T];
      }
      return c;
    },
    sample: <T>(arr: readonly T[], n: number): T[] => {
      const c = [...arr];
      const out: T[] = [];
      while (out.length < n && c.length) out.push(c.splice(Math.floor(next() * c.length), 1)[0] as T);
      return out;
    },
  };
}
